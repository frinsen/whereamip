/// The Linux readers' parsers, against captured output — the same "syscall boundary returns
/// dumb data, parsing stays pure" split the macOS readers are tested through.
final class LinuxRouteTableTests: XCTestCase {
    static let header = "Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT"

    func testOpenVPNSplitDefaultPairIsFound() {
        let table = """
        \(Self.header)
        wlp2s0\t00000000\t0102A8C0\t0003\t0\t0\t600\t00000000\t0\t0\t0
        tun0\t00000000\t0100080A\t0003\t0\t0\t0\t00000080\t0\t0\t0
        tun0\t00000080\t0100080A\t0003\t0\t0\t0\t00000080\t0\t0\t0
        """
        XCTAssertTrue(RouteTable.hijackPairPresent(procNetRoute: table))
    }

    func testOneHalfAloneIsNotThePair() {
        let table = "\(Self.header)\ntun0\t00000000\t0100080A\t0003\t0\t0\t0\t00000080\t0\t0\t0"
        XCTAssertFalse(RouteTable.hijackPairPresent(procNetRoute: table))
    }

    func testAnOrdinaryDefaultRouteIsNotThePair() {
        let table = "\(Self.header)\neth0\t00000000\t0101A8C0\t0003\t0\t0\t100\t00000000\t0\t0\t0"
        XCTAssertFalse(RouteTable.hijackPairPresent(procNetRoute: table))
    }

    func testGarbageNeverCrashesAndNeverClaimsThePair() {
        XCTAssertFalse(RouteTable.hijackPairPresent(procNetRoute: ""))
        XCTAssertFalse(RouteTable.hijackPairPresent(procNetRoute: Self.header))
        XCTAssertFalse(RouteTable.hijackPairPresent(procNetRoute: "\(Self.header)\ntun0 zz yy\n\t\t\t"))
    }
}

final class LinuxDNSConfigTests: XCTestCase {
    func testResolvectlGlobalAndPerLinkServersKeepTheirScope() {
        let output = """
        Global: 1.1.1.1#cloudflare-dns.com
        Link 2 (wlp2s0): 192.168.178.1 fd00::1 fe80::1%wlp2s0
        Link 3 (docker0):
        Link 7 (wg0): 10.64.0.1
        """
        let resolvers = LinuxDNSConfigReader.parse(resolvectlDNS: output)
        XCTAssertEqual(resolvers, [
            DNSResolver(address: "1.1.1.1", isIPv6: false, interface: nil),
            DNSResolver(address: "192.168.178.1", isIPv6: false, interface: "wlp2s0"),
            DNSResolver(address: "fd00::1", isIPv6: true, interface: "wlp2s0"),
            DNSResolver(address: "fe80::1", isIPv6: true, interface: "wlp2s0"),
            DNSResolver(address: "10.64.0.1", isIPv6: false, interface: "wg0"),
        ])
    }

    func testTheSameAddressOnTwoLinksIsTwoEntriesButOneUniqueAddress() {
        let output = "Link 2 (eth0): 192.168.1.1\nLink 3 (wlan0): 192.168.1.1 192.168.1.1"
        let resolvers = LinuxDNSConfigReader.parse(resolvectlDNS: output)
        XCTAssertEqual(resolvers.map(\.interface), ["eth0", "wlan0"])
        XCTAssertEqual(DNSInfo(resolvers: resolvers).uniqueAddressCount, 1)
    }

    func testServerTokensReduceToBareAddresses() {
        XCTAssertEqual(LinuxDNSConfigReader.serverAddress("9.9.9.9:853#dns.quad9.net"), "9.9.9.9")
        XCTAssertEqual(LinuxDNSConfigReader.serverAddress("[2620:fe::fe]:853#dns.quad9.net"), "2620:fe::fe")
        XCTAssertEqual(LinuxDNSConfigReader.serverAddress("2620:fe::fe"), "2620:fe::fe")
        XCTAssertEqual(LinuxDNSConfigReader.serverAddress("fe80::1%3"), "fe80::1")
        XCTAssertNil(LinuxDNSConfigReader.serverAddress("dns.example"))
        XCTAssertNil(LinuxDNSConfigReader.serverAddress("[2620:fe::fe"))
    }

    func testResolvConfNameserversAreGlobalAndDeduplicated() {
        let conf = """
        # Generated by NetworkManager
        search fritz.box
        nameserver 192.168.178.1
        nameserver\tfd00::1
        nameserver 192.168.178.1
        options edns0
        """
        XCTAssertEqual(LinuxDNSConfigReader.parse(resolvConf: conf), [
            DNSResolver(address: "192.168.178.1", isIPv6: false),
            DNSResolver(address: "fd00::1", isIPv6: true),
        ])
    }

    func testOnlyStrictDNSOverTLSIsReportedAsEncrypted() {
        let strict = "Global\n  Protocols: -LLMNR -mDNS +DNSOverTLS DNSSEC=no/unsupported\n"
        let opportunistic = "Global\n  Protocols: -LLMNR -mDNS DNSOverTLS=opportunistic DNSSEC=no/unsupported\n"
        let off = "Global\n  Protocols: +LLMNR -mDNS -DNSOverTLS DNSSEC=no/unsupported\n"
        XCTAssertEqual(LinuxDNSConfigReader.encryption(resolvectlStatus: strict), .dot)
        XCTAssertEqual(LinuxDNSConfigReader.encryption(resolvectlStatus: opportunistic), .unknown)
        // Off is still not evidence of plaintext end to end — see the reader's rationale.
        XCTAssertEqual(LinuxDNSConfigReader.encryption(resolvectlStatus: off), .unknown)
    }
}

final class LinuxVPNNamingTests: XCTestCase {
    func testNetworkManagerConnectionNameIsTheServiceName() {
        XCTAssertEqual(LinuxServiceNamer.connectionName(deviceShow: "GENERAL.CONNECTION:Office WireGuard\n",
                                                        interface: "wg0"), "Office WireGuard")
