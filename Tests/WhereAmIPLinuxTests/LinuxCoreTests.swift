    func testCAndPOSIXMeanNoPreferenceAndSilenceLANGUAGE() {
        XCTAssertEqual(AppLanguage.posixPreferredLanguages(environment: ["LANG": "C.UTF-8"]), [])
        XCTAssertEqual(AppLanguage.posixPreferredLanguages(environment: ["LANG": "POSIX", "LANGUAGE": "de"]), [])
        XCTAssertEqual(AppLanguage.posixPreferredLanguages(environment: [:]), [])
    }

    func testFirstSupportedHonoursOrderAndRegions() {
        XCTAssertEqual(AppLanguage.firstSupported(in: ["de-AT", "en"]), "de")
        XCTAssertEqual(AppLanguage.firstSupported(in: ["fr-FR", "de_DE"]), "de")
