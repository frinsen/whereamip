        XCTAssertEqual(AppLanguage.posixPreferredLanguages(environment: ["LANG": "de_DE.UTF-8"]), ["de-DE"])
        XCTAssertEqual(AppLanguage.posixPreferredLanguages(environment: ["LANG": "de_DE@euro"]), ["de-DE"])
