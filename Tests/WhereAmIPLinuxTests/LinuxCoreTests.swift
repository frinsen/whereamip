        XCTAssertEqual(LinuxServiceNamer.activeConnections(terse: output), [
            .init(name: "Home Wi:Fi", uuid: "6f1c-uuid", type: "802-11-wireless"),
            .init(name: "Office", uuid: "9a2e-uuid", type: "vpn"),
        ])
    }

    func testVendorAssignedInterfaceNamesIdentifyTheirVendor() {
        XCTAssertEqual(LinuxServiceNamer.vendorInterfaceName("tailscale0"), "Tailscale")
        XCTAssertEqual(LinuxServiceNamer.vendorInterfaceName("CloudflareWARP"), "Cloudflare WARP")
        XCTAssertEqual(LinuxServiceNamer.vendorInterfaceName("nordlynx"), "NordVPN")
        XCTAssertEqual(LinuxServiceNamer.vendorInterfaceName("wg0-mullvad"), "Mullvad")
    }

    func testAmbiguousDefaultsNameNobody() {
        for generic in ["tun0", "wg0", "ppp0", "tap0", "office"] {
            XCTAssertNil(LinuxServiceNamer.vendorInterfaceName(generic), generic)
        }
    }

    func testTunnelDetectionIsStructural() {
        XCTAssertTrue(LinuxTunnel.isTunnel(devType: "wireguard", arphrdType: 65534))
        XCTAssertTrue(LinuxTunnel.isTunnel(devType: nil, arphrdType: 65534))      // TUN
        XCTAssertTrue(LinuxTunnel.isTunnel(devType: nil, arphrdType: 512))        // PPP
        XCTAssertTrue(LinuxTunnel.isTunnel(devType: nil, arphrdType: 768))        // ipip / vti
        XCTAssertFalse(LinuxTunnel.isTunnel(devType: "wlan", arphrdType: 1))
        XCTAssertFalse(LinuxTunnel.isTunnel(devType: nil, arphrdType: 772))       // loopback
        XCTAssertFalse(LinuxTunnel.isTunnel(devType: nil, arphrdType: nil))
    }

    func testCommonTunnelNamesAreTunnelsAndAMissingLinkIsNot() {
        for name in ["tun0", "wg0", "tailscale0", "nordlynx", "utun4", "ppp0"] {
            XCTAssertTrue(RouteInspector.isTunnelInterface(name), name)
        }
        XCTAssertFalse(RouteInspector.isTunnelInterface("zzz-no-such-link"))
    }

    /// The macOS ladder, fed Linux evidence: a vendor-named interface fills the service-name
    /// slot, and an unnamed generic tunnel falls downward to the honest generic label.
    func testTheNamingLadderWithLinuxEvidence() {
        XCTAssertEqual(VPNNamer.name(interface: "tailscale0", localAddress: "100.101.102.103",
                                     scServiceName: LinuxServiceNamer.vendorInterfaceName("tailscale0"),
                                     runningBundleIDs: []), "Tailscale")
        XCTAssertEqual(VPNNamer.name(interface: "tun0", localAddress: "10.8.0.2", scServiceName: nil,
