final class LinuxSettingsTests: XCTestCase {
    /// Field-found on Linux: corelibs Foundation writes preferences only on synchronize(),
    /// so a setter that skipped it — and every `whereamip config set` — changed nothing.
    func testASetterReachesTheFileWithoutAnyoneCallingSynchronize() throws {
        let suite = "io.github.frinsen.whereamip.tests.\(UUID().uuidString)"
        // Wherever this Foundation keeps preferences: $XDG_CONFIG_HOME, or .config in home.
        let environment = ProcessInfo.processInfo.environment
        let candidates = [environment["XDG_CONFIG_HOME"], environment["HOME"].map { "\($0)/.config" },
                          "\(NSHomeDirectory())/.config"].compactMap { $0 }.map { "\($0)/\(suite).plist" }
            .reduce(into: [String]()) { if !$0.contains($1) { $0.append($1) } }
        defer { for file in candidates { try? FileManager.default.removeItem(atPath: file) } }
        let settings = Settings(defaults: try XCTUnwrap(UserDefaults(suiteName: suite)))
        settings.menuBarStyle = .code
        let written = candidates.compactMap { try? String(contentsOfFile: $0, encoding: .utf8) }
        XCTAssertEqual(written.count, 1, "no preferences file in \(candidates)")
        XCTAssertTrue(written.first?.contains("code") == true)
    }
}

final class LinuxDesktopEntryTests: XCTestCase {
    var tmp: String!

    override func setUpWithError() throws {
        tmp = NSTemporaryDirectory() + "LinuxDesktopEntryTests-\(UUID().uuidString)"
        try FileManager.default.createDirectory(atPath: tmp, withIntermediateDirectories: true)
    }

    override func tearDown() {
        try? FileManager.default.removeItem(atPath: tmp)
    }

    func testPathsFollowXDGWithTheSpecDefaults() {
        XCTAssertEqual(LinuxDesktopEntry.path(.launcher, environment: [:], home: "/home/u"),
                       "/home/u/.local/share/applications/io.github.frinsen.whereamip.desktop")
        XCTAssertEqual(LinuxDesktopEntry.path(.autostart, environment: [:], home: "/home/u"),
                       "/home/u/.config/autostart/io.github.frinsen.whereamip.desktop")
        XCTAssertEqual(LinuxDesktopEntry.path(.autostart, environment: ["XDG_CONFIG_HOME": "/cfg"], home: "/home/u"),
                       "/cfg/autostart/io.github.frinsen.whereamip.desktop")
        // A relative XDG value is invalid per the spec and ignored.
        XCTAssertEqual(LinuxDesktopEntry.path(.launcher, environment: ["XDG_DATA_HOME": "rel"], home: "/home/u"),
                       "/home/u/.local/share/applications/io.github.frinsen.whereamip.desktop")
    }

    func testContentsAreAValidEntryThatOnlyAutostartMarksAsSuch() {
        let launcher = LinuxDesktopEntry.contents(kind: .launcher, executable: "/opt/w/whereamip-indicator")
        XCTAssertTrue(launcher.hasPrefix("[Desktop Entry]\n"))
        XCTAssertTrue(launcher.contains("\nExec=/opt/w/whereamip-indicator\n"))
        XCTAssertTrue(launcher.contains("\nIcon=io.github.frinsen.whereamip\n"))
        XCTAssertTrue(launcher.contains("\n\(LinuxDesktopEntry.managedMarker)\n"))
        XCTAssertFalse(launcher.contains("Autostart"))
        XCTAssertTrue(LinuxDesktopEntry.contents(kind: .autostart, executable: "/x").contains("X-GNOME-Autostart-enabled=true"))
    }

    func testExecQuotingFollowsTheDesktopEntrySpec() {
        XCTAssertEqual(LinuxDesktopEntry.execValue("/home/u/.local/lib/whereamip/whereamip-indicator"),
                       "/home/u/.local/lib/whereamip/whereamip-indicator")
        XCTAssertEqual(LinuxDesktopEntry.execValue("/home/u/My Apps/w"), "\"/home/u/My Apps/w\"")
        XCTAssertEqual(LinuxDesktopEntry.execValue("/a$b"), "\"/a\\\\$b\"")
        XCTAssertEqual(LinuxDesktopEntry.execValue("/100%"), "\"/100%%\"")
    }

    func testOnOffIsIdempotentAndOnlyEverTouchesItsOwnEntry() throws {
        let path = "\(tmp!)/apps/io.github.frinsen.whereamip.desktop"
        XCTAssertFalse(LinuxDesktopEntry.isInstalled(at: path))
        try LinuxDesktopEntry.setInstalled(true, kind: .launcher, executable: "/old/whereamip-indicator", at: path)
        try LinuxDesktopEntry.setInstalled(true, kind: .launcher, executable: "/new/whereamip-indicator", at: path)
        XCTAssertTrue(try String(contentsOfFile: path, encoding: .utf8).contains("Exec=/new/whereamip-indicator"))
        try LinuxDesktopEntry.setInstalled(false, kind: .launcher, executable: "/new/whereamip-indicator", at: path)
        XCTAssertFalse(LinuxDesktopEntry.isInstalled(at: path))
        try LinuxDesktopEntry.setInstalled(false, kind: .launcher, executable: "/x", at: path)   // absent: no-op

        try "[Desktop Entry]\nName=Someone else's\n".write(toFile: path, atomically: true, encoding: .utf8)
        XCTAssertTrue(LinuxDesktopEntry.isInstalled(at: path))
        XCTAssertThrowsError(try LinuxDesktopEntry.setInstalled(false, kind: .launcher, executable: "/x", at: path))
        XCTAssertThrowsError(try LinuxDesktopEntry.setInstalled(true, kind: .launcher, executable: "/x", at: path))
        XCTAssertTrue(try String(contentsOfFile: path, encoding: .utf8).contains("Someone else's"))
    }

    func testTheIndicatorIsFoundNextToTheCLIThroughASymlink() throws {
        let lib = "\(tmp!)/lib", bin = "\(tmp!)/bin"
        for dir in [lib, bin] { try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true) }
        for exe in ["whereamip", "whereamip-indicator"] {
            FileManager.default.createFile(atPath: "\(lib)/\(exe)", contents: Data("#!/bin/sh\n".utf8),
                                           attributes: [.posixPermissions: 0o755])
        }
        try FileManager.default.createSymbolicLink(atPath: "\(bin)/whereamip", withDestinationPath: "\(lib)/whereamip")
        let found = LinuxDesktopEntry.indicatorExecutable(nextTo: "\(bin)/whereamip")
        XCTAssertEqual(found.map { URL(fileURLWithPath: $0).resolvingSymlinksInPath().path },
                       URL(fileURLWithPath: "\(lib)/whereamip-indicator").resolvingSymlinksInPath().path)
        XCTAssertNil(LinuxDesktopEntry.indicatorExecutable(nextTo: "\(tmp!)/nowhere/whereamip"))
    }
}
