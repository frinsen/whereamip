/// The DNS wire format under the egress probe, built byte by byte — no network involved.
final class DNSResponseParserTests: XCTestCase {
    static func name(_ dotted: String) -> [UInt8] {
        dotted.split(separator: ".").flatMap { [UInt8($0.utf8.count)] + Array($0.utf8) } + [0]
    }
    static func u16(_ v: Int) -> [UInt8] { [UInt8(v >> 8), UInt8(v & 0xFF)] }
    static func txt(_ strings: [String]) -> [UInt8] { strings.flatMap { [UInt8($0.utf8.count)] + Array($0.utf8) } }

    static func response(answers: [[UInt8]]) -> [UInt8] {
        var m: [UInt8] = [0x12, 0x34, 0x81, 0x80]          // id, flags: response, no error
        for count in [1, answers.count, 0, 0] { m += u16(count) }
        m += name("abc123.test.dnscheck.tools")
        m += u16(16)
        m += u16(1)
        for answer in answers { m += answer }
        return m
    }

    static func record(type: Int, rdata: [UInt8], owner: [UInt8] = [0xC0, 0x0C]) -> [UInt8] {
        var r = owner
        r += u16(type)
        r += u16(1)                                          // class IN
        r += [0, 0, 0, 60]                                   // TTL
        r += u16(rdata.count)
        r += rdata
        return r
    }

    func testTXTStringsOfEveryAnswerRecord() {
        let message = Self.response(answers: [
            Self.record(type: 16, rdata: Self.txt(["FROM: 74.80.89.244#39071 WoodyNet, Inc. (Berlin, DE)", "PROTO: UDP"])),
        ])
        XCTAssertEqual(DNSEgressProbe.parseTXTResponse(message),
                       ["FROM: 74.80.89.244#39071 WoodyNet, Inc. (Berlin, DE)", "PROTO: UDP"])
    }

    func testACNAMEInFrontOfTheTXTRecordIsSkipped() {
        let message = Self.response(answers: [
            Self.record(type: 5, rdata: Self.name("o-o.myaddr.l.google.com")),
            Self.record(type: 16, rdata: Self.txt(["203.0.113.9"]), owner: Self.name("o-o.myaddr.l.google.com")),
        ])
        XCTAssertEqual(DNSEgressProbe.parseTXTResponse(message), ["203.0.113.9"])
        XCTAssertEqual(DNSEgressProbe.parseAnswer(txtStrings: DNSEgressProbe.parseTXTResponse(message))?.ip, "203.0.113.9")
    }

    func testTruncatedOrEmptyMessagesYieldWhatParsedAndNeverCrash() {
        let full = Self.response(answers: [Self.record(type: 16, rdata: Self.txt(["one"])),
                                           Self.record(type: 16, rdata: Self.txt(["two"]))])
        XCTAssertEqual(DNSEgressProbe.parseTXTResponse(full), ["one", "two"])
        XCTAssertEqual(DNSEgressProbe.parseTXTResponse(Array(full.dropLast(2))), ["one"])
        for cut in 0..<full.count { _ = DNSEgressProbe.parseTXTResponse(Array(full.prefix(cut))) }
        XCTAssertEqual(DNSEgressProbe.parseTXTResponse([]), [])
        XCTAssertEqual(DNSEgressProbe.parseTXTResponse(Self.response(answers: [])), [])
    }
}

final class AppLanguageLinuxTests: XCTestCase {
