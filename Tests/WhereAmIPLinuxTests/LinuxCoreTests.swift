        XCTAssertEqual(AppLanguage.posixPreferredLanguages(environment: ["LANG": "en_US.UTF-8", "LC_MESSAGES": "de_DE.UTF-8"]),
                       ["de-DE"])
        XCTAssertEqual(AppLanguage.posixPreferredLanguages(environment: ["LANGUAGE": "de:en_GB", "LANG": "de_DE.UTF-8"]),
